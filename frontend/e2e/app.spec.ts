import { test, expect } from '@playwright/test'
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const email='browser@example.com'
test('full account, dictionary, lesson, routing, export and logout flow',async ({page,context}) => {
  const errors: string[]=[]
  page.on('pageerror',e => errors.push(e.message))
  await page.goto('/translate')
  await page.getByRole('tab',{name:'حساب جديد'}).click()
  await page.getByLabel('الاسم',{exact:true}).fill('مريم')
  await page.getByLabel('البريد الإلكتروني',{exact:true}).fill(email)
  await page.getByLabel('كلمة المرور',{exact:true}).fill('browser-password')
  await page.getByRole('button',{name:'إنشاء الحساب',exact:true}).click()
  await expect(page.getByRole('heading',{name:'مساحة الترجمة',exact:true})).toBeVisible()
  const cookie=(await context.cookies()).find(c => c.name==='signbridge_session')
  expect(cookie?.httpOnly).toBe(true)
  expect(await page.evaluate(() => localStorage.getItem('signbridge-token'))).toBeNull()
  await page.getByLabel('النص المراد ترجمته').fill('صباح الخير عامل إيه موز')
  await page.getByRole('button',{name:'عرض الإشارات',exact:true}).click()
  await expect(page.getByText(/غير متاح في القاموس: موز/)).toBeVisible()
  const video=page.getByLabel('إشارة صباح الخير')
  await expect(video).toBeVisible()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2)
  await page.getByRole('button',{name:'تشغيل التسلسل'}).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeGreaterThan(0)
  await page.screenshot({path:'test-results/translation-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'التالي',exact:true}).click()
  await expect(page.getByLabel('إشارة عامل إيه')).toBeVisible()
  await page.getByLabel('ملاحظة على هذه النتيجة').fill('مراجعة اختبارية للفيديو')
  await page.getByRole('button',{name:'إرسال الملاحظة'}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'تنزيل الكل'}).click()
  expect((await download).suggestedFilename()).toBe('signbridge-history.json')
  await page.getByRole('button',{name:'مركز التعلّم',exact:true}).first().click()
  await expect(page).toHaveURL(/\/learn$/)
  await page.locator('article').filter({has:page.getByRole('heading',{name:'التحيات بالفيديو',exact:true})}).getByRole('button',{name:'فتح الدرس',exact:true}).click()
  await expect(page).toHaveURL(/lesson=dictionary-1/)
  await page.reload()
  const dialog=page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  const manifest=JSON.parse(readFileSync('../backend/signs.json','utf8'))
  const signs=manifest.filter((s: {category:string}) => s.category==='التحيات')
  const fields=dialog.locator('fieldset')
  for(let i=0;i<signs.length;i++) await fields.nth(i).getByLabel(signs[i].gloss,{exact:true}).check()
  await dialog.getByRole('button',{name:'تصحيح وحفظ النتيجة'}).click()
  await expect(dialog.getByRole('status')).toContainText('100%')
  await dialog.getByRole('button',{name:'إغلاق'}).click()
  await page.getByRole('button',{name:'حفظ الإشارة',exact:true}).first().click()
  await expect(page.getByRole('button',{name:'إزالة من المحفوظات',exact:true}).first()).toBeVisible()
  await page.goto('/saved')
  await expect(page.getByLabel('إشارة عامل إيه')).toBeVisible()
  await page.goto('/translate')
  await page.reload()
  await expect(page.getByRole('heading',{name:'مساحة الترجمة',exact:true})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.getByLabel('النص المراد ترجمته').fill('صباح الخير')
  await page.getByRole('button',{name:'عرض الإشارات',exact:true}).click()
  await expect(page.getByLabel('إشارة صباح الخير')).toBeVisible()
  await expect.poll(() => page.getByLabel('إشارة صباح الخير').evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2)
  await page.screenshot({path:'test-results/translation-mobile.png',fullPage:true,animations:'disabled'})
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.goto('/privacy')
  await expect(page.getByRole('heading',{name:'الخصوصية وحدود الخدمة'})).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/\/translate$/)
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'تسجيل الخروج'}).click()
  await expect(page.getByRole('button',{name:'دخول',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})

test('password reset page provides a real email request flow',async ({page}) => {
  await page.goto('/forgot-password')
  await page.getByLabel('البريد الإلكتروني').fill(email)
  await page.getByRole('button',{name:'إرسال رابط الاستعادة'}).click()
  await expect(page.getByRole('status')).toContainText('هتوصلك رسالة')
  let bodies: string[]=[]
  if (process.env.MAILPIT_BIN) {
    const listing=await (await page.request.get('http://127.0.0.1:18025/api/v1/messages')).json()
    expect(listing.messages.length).toBeGreaterThanOrEqual(2)
    for(const item of listing.messages) {
      const message=await (await page.request.get('http://127.0.0.1:18025/api/v1/message/'+item.ID)).json()
      bodies.push(message.Text)
    }
    const inbox=await page.context().newPage()
    await inbox.goto('http://127.0.0.1:18025')
    await expect(inbox.getByText('SignBridge: استعادة كلمة المرور',{exact:true})).toBeVisible()
    await inbox.screenshot({path:'test-results/mailpit-inbox.png',fullPage:true,animations:'disabled'})
    await inbox.close()
  } else {
    const outbox=join(process.env.SB_E2E_DATA!,'dev-outbox')
    const files=readdirSync(outbox).filter(f => f.endsWith('.eml'))
    expect(files.length).toBeGreaterThanOrEqual(2)
    bodies=files.map(f => {
      const raw=readFileSync(join(outbox,f),'utf8')
      const split=raw.split(/\r?\n\r?\n/)
      const body=split.slice(1).join('\n\n')
      return raw.includes('Content-Transfer-Encoding: base64')?Buffer.from(body.replace(/\s/g,''),'base64').toString('utf8'):body.replace(/=\r?\n/g,'')
    })
  }
  const verify=bodies.find(body => body.includes('purpose=verify'))!
  const verifyUrl=verify.match(/http:\/\/127\.0\.0\.1:8099\/account-action\?\S+/)![0]
  await page.goto(verifyUrl)
  await page.getByRole('button',{name:'تأكيد',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('تم تأكيد البريد')
  const reset=bodies.find(body => body.includes('purpose=reset'))!
  const url=reset.match(/http:\/\/127\.0\.0\.1:8099\/account-action\?\S+/)![0]
  await page.goto(url)
  await page.getByLabel('كلمة المرور الجديدة، 8 أحرف على الأقل').fill('recovered-password')
  await page.getByRole('button',{name:'تأكيد',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('تم تغيير كلمة المرور')
  await page.goto('/')
  await page.getByLabel('البريد الإلكتروني',{exact:true}).fill(email)
  await page.getByLabel('كلمة المرور',{exact:true}).fill('recovered-password')
  await page.getByRole('button',{name:'دخول',exact:true}).click()
  await expect(page.getByRole('heading',{name:/أهلاً/})).toBeVisible()
  await page.goto('/docs')
  await expect(page.getByRole('heading',{name:'SignBridge API'})).toBeVisible()
})
